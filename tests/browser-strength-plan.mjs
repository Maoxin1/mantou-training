import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdir} from 'node:fs/promises';
import {chromium} from 'playwright';
const port='4193',baseUrl=process.env.TRAINING_BASE_URL||`http://127.0.0.1:${port}/`;
const server=process.env.TRAINING_BASE_URL?null:spawn(process.execPath,['scripts/serve.mjs'],{env:{...process.env,PORT:port},stdio:['ignore','pipe','inherit']});
let browser;
try{
  if(server)await new Promise((resolve,reject)=>{server.stdout.once('data',resolve);server.once('error',reject);server.once('exit',code=>reject(Error('Server exited '+code)));});
  browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL||(process.platform==='win32'?'msedge':undefined),headless:true});
  const context=await browser.newContext({viewport:{width:390,height:844}}),page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));page.setDefaultTimeout(5000);
  await page.goto(baseUrl);
  const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('mantou-training-v1')));
  await page.click('#startTrial');await page.click('#startTrialForm button[type=submit]');
  await page.click('#beginSession');await page.click('#closeDialog');
  const before=await read(),oldId=before.journal.settings.activeTrial;
  await page.click('#startStrength');
  assert.match(await page.locator('#dialogTitle').innerText(),/三日力量/);
  await page.click('#closeDialog');assert.deepEqual(await read(),before,'T04-M07: cancel must not create a phase');
  await page.click('#startStrength');await page.click('#confirmStrength');
  let s=await read(),phase=s.journal.trials[s.journal.settings.activeTrial];
  assert.equal(phase.routine,'strength3-v1');assert.equal(phase.end,null);
  assert.deepEqual(s.journal.trials[oldId],before.journal.trials[oldId]);
  assert.deepEqual(s.journal.entries,before.journal.entries);
  await page.selectOption('#strengthWorkout','B');
  await page.click('#beginSession');await page.click('#closeDialog');
  s=await read();let current=Object.values(s.journal.entries).filter(e=>e.kind==='session'&&e.fields.trialId===phase.id).at(-1);
  assert.equal(current.fields.workout,'B');
  assert.deepEqual(current.fields.plan.map(e=>e.id),['dbrow','push','rdl','lateral','rear']);
  await page.click('[data-journal-exercise=dbrow]');
  await page.locator('[data-row="0"][data-key=left]').fill('10');
  await page.locator('[data-row="0"][data-key=right]').fill('9');
  await page.locator('[data-row="0"][data-key=rir]').selectOption('4');
  await page.click('#closeDialog');
  await page.click('#adjustTrial');
  await page.locator('#adjustTrialForm details').nth(1).locator('summary').click();
  await page.locator('[data-field="1-min"]').fill('7');
  await page.locator('[data-field=reason]').fill('验收：只影响确认后新建场次');
  await page.click('#adjustTrialForm button[type=submit]');await page.click('#confirmAdjust');
  s=await read();assert.equal(s.journal.entries[current.id].fields.plan.find(e=>e.id==='push').min,6);
  await page.click('#newSession');await page.selectOption('#newStrengthSessionForm [data-field=workout]','C');
  await page.click('#newStrengthSessionForm button[type=submit]');await page.click('#closeDialog');
  s=await read();const newest=Object.values(s.journal.entries).filter(e=>e.kind==='session'&&e.fields.trialId===phase.id).at(-1);
  assert.equal(newest.fields.workout,'C');assert.equal(newest.fields.plan.find(e=>e.id==='push').min,7);
  assert.deepEqual(s.journal.entries[Object.keys(before.journal.entries)[0]],Object.values(before.journal.entries)[0]);
  await page.click('#quickReview');assert.match(await page.locator('.review-preview').innerText(),/三日力量训练周复盘/);
  await page.click('#closeDialog');
  await page.click('[data-page=history]');await page.locator('#journalDate').fill('2020-01-01');
  await page.locator('#journalDate').dispatchEvent('change');await page.click('#reviewTrialButton');
  await page.getByText('所选日期早于阶段开始，请选择开始后的日期，或切换到原试行阶段',{exact:true}).waitFor();
  assert.equal(await page.locator('#exerciseDialog').isVisible(),false);
  await page.click('[data-page=plan]');
  await page.evaluate(()=>navigator.serviceWorker.ready.then(()=>true));
  await context.setOffline(true);await page.reload();
  assert.equal((await read()).journal.trials[phase.id].routine,'strength3-v1');
  await page.click('#todayFeedback');await page.click('[data-meal=lunch]');
  assert.equal(await page.locator('#mealFile').count(),1,'meal photo input remains available');
  await page.click('#closeDialog');await context.setOffline(false);
  await page.setViewportSize({width:820,height:1180});await page.reload();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await mkdir('test-output',{recursive:true});await page.screenshot({path:'test-output/strength-tablet.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'test-output/strength-phone.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS T04-M07/M08: canceled preview, explicit activation, A/B/C snapshots, future-only adjustment, per-side records, weekly review, offline restart, meal entry, phone/tablet layout.');
}finally{await browser?.close();server?.kill();}
